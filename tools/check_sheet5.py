from sympy import *
x,t=symbols('x t'); y=Function('y')
def show(name,eq,var,ics=None):
    try:
        s=dsolve(eq,y(var),ics=ics) if ics else dsolve(eq,y(var))
    except Exception as e: s=str(e)
    print(name,':',s)
show('1a',Eq(y(t).diff(t),t*y(t)),t,{y(0):1})
show('1b',Eq(y(t).diff(t),1-y(t)),t,{y(0):0})
show('2a',Eq(y(x).diff(x),(1+x)*(1+y(x))),x)
show('2b',Eq(y(t).diff(t),exp(-y(t))*t**2),t)
show('2c',Eq(y(x).diff(x),1+x**2+y(x)+x**2*y(x)),x)
show('2d',Eq(y(x).diff(x)+2*x*y(x),x*exp(-x**2)),x)
show('2e',Eq(y(x).diff(x)+2*y(x)/x,1/x**2),x)
show('2f',Eq(y(x).diff(x)+x*y(x),x/y(x)),x)
for n,(a,b,c) in zip('abcd',[(1,3,2),(1,-9,0),(1,10,25),(1,2,2)]):
    show('3'+n,Eq(a*y(x).diff(x,2)+b*y(x).diff(x)+c*y(x),0),x)
show('4a',Eq(y(x).diff(x,2)-y(x),3*x**2),x)
show('4b',Eq(y(x).diff(x,2)+4*y(x).diff(x)-5*y(x),x**2),x)
show('4c',Eq(y(x).diff(x,2)-y(x).diff(x)-2*y(x),exp(x)+x),x)
show('4d',Eq(y(t).diff(t,2)+6*y(t).diff(t)+9*y(t),16*t*exp(t)),t)
show('4e',Eq(y(x).diff(x,2)-2*y(x).diff(x)+y(x),x**3+x**2),x)
show('4f',Eq(y(x).diff(x,2)-4*y(x).diff(x)+4*y(x),(3*x**2+2)*exp(x)),x)
show('5a',Eq(y(x).diff(x,2)-16*y(x),0),x,{y(0):1,y(x).diff(x).subs(x,0):20})
show('5b',Eq(y(x).diff(x,2)-y(x).diff(x)-2*y(x),3*exp(2*x)),x,{y(0):0,y(x).diff(x).subs(x,0):-2})
show('5c',Eq(y(x).diff(x,2)-4*y(x).diff(x)+3*y(x),4*exp(3*x)),x,{y(0):-1,y(x).diff(x).subs(x,0):3})
show('6a',Eq(y(x).diff(x,2)-9*y(x).diff(x)+20*y(x),3),x)
show('6b',Eq(y(x).diff(x,2)-5*y(x).diff(x)+6*y(x),5*x+1),x)
show('6c',Eq(2*y(x).diff(x,2)+y(x).diff(x)-y(x),4*x),x)
show('7a',Eq(y(t).diff(t,4)-16*y(t),30*sin(t)),t,{y(0):0,y(t).diff(t).subs(t,0):2,y(t).diff(t,2).subs(t,pi):0,y(t).diff(t,3).subs(t,pi):-18})
show('7b',Eq(y(t).diff(t,4)-16*y(t),30*sin(2*t)),t)
show('7c',Eq(y(t).diff(t,3)+y(t).diff(t,2)+y(t).diff(t)+y(t),t),t,{y(0):0,y(t).diff(t).subs(t,0):0,y(t).diff(t,2).subs(t,0):0})
D=lambda k: y(x).diff(x,k)
show('8a',Eq(D(3)+4*D(2)-D(1)-4*y(x),0),x)
show('8b',Eq(D(3)+4*D(2)-3*D(1)-18*y(x),0),x)
show('8c',Eq(D(3)+6*D(2)+12*D(1)+8*y(x),0),x)
show('8d',Eq(D(3)+4*D(2)-7*D(1)-10*y(x),0),x,{y(0):-3,D(1).subs(x,0):12,D(2).subs(x,0):-36})
show('8e',Eq(D(3)+4*D(2)-7*D(1)-10*y(x),100*x**2-64*exp(3*x)),x,{y(0):-20,D(1).subs(x,0):Rational(-29,5),D(2).subs(x,0):Rational(19,5)})
show('8f',Eq(D(3)-5*D(2)-D(1)+5*y(x),10*x-63*exp(-2*x)+29*sin(2*x)),x)
show('8g',Eq(D(4)+8*D(2)+16*y(x),0),x,{y(0):-1,D(1).subs(x,0):5,D(2).subs(x,0):-8,D(3).subs(x,0):-28})
show('8h',Eq(D(4)+8*D(2)+16*y(x),64*x*sin(2*x)),x)
show('8i',Eq(D(4)+2*D(3)-2*D(1)-y(x),24*x*exp(-x)+24*exp(x)-8*sin(x)),x,{y(0):-2,D(1).subs(x,0):0,D(2).subs(x,0):6,D(3).subs(x,0):10})
show('8j',Eq(D(4)+18*D(2)+81*y(x),64*x*cos(x)+108*x*cos(3*x)),x)
show('exam',Eq(y(t).diff(t,2)+4*y(t),t**2+cos(t)),t)
